//! The one caller template and planner: consumer repositories hold only inputs
//! and the generated workflow, never another generator.
const std = @import("std");
const src = @import("source.zig");
const zon = @import("../zon.zig");
const matrix = @import("matrix.zig");

const template = @embedFile("caller.yml");
/// The line every generated caller starts with, up to how it was generated: the
/// configuration, then the `generate` command that wrote it (`heading` below).
pub const header = "# Generated by preflight from ";

comptime {
    std.debug.assert(std.mem.startsWith(u8, template, header ++ "@WORKFLOW@\n"));
}
/// The caller's usual place, from the repository's top.
pub const default_path = ".github/workflows/ci.yml";
/// How a caller was generated, as its first line records it after `header`:
/// `<config>: bay generate`, then after ` -- ` what `generate` was given beyond its
/// defaults (`--self`, `--workflow <path>`, `--config <config>`, `--working-directory <directory>`).
pub fn heading(a: std.mem.Allocator, config: ?[]const u8, path: []const u8, working_directory: ?[]const u8, own: bool) ![]const u8 {
    var flags: std.Io.Writer.Allocating = .init(a);
    if (own) try flags.writer.writeAll(" --self");
    if (!std.mem.eql(u8, path, default_path)) try flags.writer.print(" --workflow {s}", .{path});
    if (config) |given| try flags.writer.print(" --config {s}", .{given});
    if (working_directory) |given| try flags.writer.print(" --working-directory {s}", .{given});
    const given = flags.written();
    return a.print("{s}: bay generate{s}{s}", .{ config orelse "ci/workflow.json", if (given.len == 0) "" else " --", given });
}

/// What a caller's first line says it was generated with; null for a file preflight did not generate.
pub const Planned = struct { config: []const u8, working_directory: ?[]const u8 };

/// The commands a caller's first line has named: `generate`'s, and `plan --workflow`'s before
/// it (preflight 0.16.0 and earlier), so a caller from then is found and generated again.
const commands = [_][]const u8{ ": bay generate", ": zig build plan -- " };

pub fn planned(text: []const u8) ?Planned {
    if (!std.mem.startsWith(u8, text, header)) return null;
    const line = text[header.len .. std.mem.findScalar(u8, text, '\n') orelse text.len];
    for (commands) |command| {
        const at = std.mem.find(u8, line, command) orelse continue;
        var result: Planned = .{ .config = line[0..at], .working_directory = null };
        var words = std.mem.tokenizeScalar(u8, line[at + command.len ..], ' ');
        while (words.next()) |word| {
            if (std.mem.eql(u8, word, "--working-directory")) result.working_directory = words.next();
        }
        return result;
    }
    return null;
}

test "a caller's first line says how it was generated, with no flags or with them" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const plain = try heading(a, null, default_path, null, false);
    try std.testing.expectEqualStrings("ci/workflow.json: bay generate", plain);
    const read = planned(try std.mem.concat(a, u8, &.{ header, plain, "\nname: CI\n" })).?;
    try std.testing.expectEqualStrings("ci/workflow.json", read.config);
    try std.testing.expect(read.working_directory == null);
    const elsewhere = try heading(a, "sample/ci/workflow.json", default_path, "sample", true);
    try std.testing.expectEqualStrings("sample/ci/workflow.json: bay generate -- --self --config sample/ci/workflow.json --working-directory sample", elsewhere);
    const there = planned(try std.mem.concat(a, u8, &.{ header, elsewhere, "\n" })).?;
    try std.testing.expectEqualStrings("sample/ci/workflow.json", there.config);
    try std.testing.expectEqualStrings("sample", there.working_directory.?);
    // A caller `plan --workflow` generated, before `generate`, is still read.
    const old = planned(header ++ "sample/ci/workflow.json: zig build plan -- --self --workflow .github/workflows/ci.yml --config sample/ci/workflow.json --working-directory sample\nname: CI\n").?;
    try std.testing.expectEqualStrings("sample/ci/workflow.json", old.config);
    try std.testing.expectEqualStrings("sample", old.working_directory.?);
    try std.testing.expect(planned("name: CI\n") == null);
}

const repository = "git+https://github.com/pedronaugusto/preflight";
/// A package pins preflight as a dev dependency with bay, or as a dependency without it.
const Pinned = struct { preflight: ?struct { url: ?[]const u8 = null } = null };
const Manifest = struct {
    dependencies: Pinned = .{},
    dev_dependencies: Pinned = .{},
};

pub fn pinned(c: src.Context, manifest_path: []const u8) ![]const u8 {
    var diagnostics: std.zon.parse.Diagnostics = .{ .errors = &.{} };
    const manifest = try std.zon.parse.fromSlice(Manifest, .{
        .gpa = c.a,
        .arena = c.a,
        .source = (try zon.source(c.a, try c.read(manifest_path))) orelse return error.InvalidManifest,
        .diagnostics = &diagnostics,
        .ignore_unknown_fields = true,
    });
    const entry = manifest.dev_dependencies.preflight orelse manifest.dependencies.preflight orelse return error.MissingPublishedPreflightPin;
    const url = entry.url orelse return error.MissingPublishedPreflightPin;
    if (!std.mem.startsWith(u8, url, repository)) return error.InvalidPreflightRepository;
    // A pin by release names the tag before the commit (`?ref=v0.2.0#<commit>`), as
    // `zig fetch` and bay write it; the commit after `#` is what the caller pins.
    const pinned_ref = url[repository.len..];
    const pin = if (std.mem.startsWith(u8, pinned_ref, "#"))
        pinned_ref[1..]
    else if (std.mem.startsWith(u8, pinned_ref, "?ref=")) tagged: {
        const hash = std.mem.findScalar(u8, pinned_ref, '#') orelse return error.InvalidPreflightPin;
        if (hash == "?ref=".len) return error.InvalidPreflightPin;
        break :tagged pinned_ref[hash + 1 ..];
    } else return error.InvalidPreflightRepository;
    if (pin.len != 40) return error.InvalidPreflightPin;
    for (pin) |byte| if (!std.ascii.isHex(byte) or std.ascii.isUpper(byte)) return error.InvalidPreflightPin;
    return pin;
}

/// The configuration at `path`, with what the last merge or release run measured
/// (`costs.json` beside it) as `measured`.
pub fn configuration(c: src.Context, path: []const u8) !src.Value {
    var config = try c.options(path);
    const costs = try std.Io.Dir.path.join(c.a, &.{ std.Io.Dir.path.dirname(path) orelse ".", "costs.json" });
    if (config == .object and try c.exists(costs)) try config.object.put(c.a, "measured", try c.json(costs));
    return config;
}

/// The caller `config` generates for the package whose manifest is `manifest`, gated in
/// `directory`, pinned to that manifest's preflight (to the commit under test with `own`),
/// headed with `label`. With `existing`, the caller it replaces, a job of that caller the
/// configuration does not declare, and `drops` does not name, refuses it.
pub fn generate(c: src.Context, config: src.Value, manifest: []const u8, directory: []const u8, own: bool, label: []const u8, existing: ?[]const u8, drops: []const []const u8) ![]const u8 {
    const pin = if (own) "" else try pinned(c, manifest);
    const text = try render(c.a, config, pin, directory, own, label);
    if (existing) |old| try keepsEveryJob(old, text, drops);
    return text;
}

/// The jobs of an earlier caller that its generator wrote, and so may go: `land` is the one a
/// caller generated before releases moved to bay held, which goes when it is generated again.
const generated_jobs = [_][]const u8{ "gate", "land", "checks", "skip" };

/// The last job `keepsEveryJob` refused to drop, for the command to name: the refusing thread's own.
pub threadlocal var undeclared: []const u8 = "";

/// Refuses to replace `existing` while it holds a job `generated` does not, unless
/// `drops` names it, as `--drop` does for one the configuration now declares: the
/// generator owns the whole caller, and a package's own job is declared in
/// `ci/workflow.json` `jobs`, so it is rendered with the gate and a landing
/// waits for it. Nothing is dropped unseen.
pub fn keepsEveryJob(existing: []const u8, generated: []const u8, drops: []const []const u8) !void {
    var missing = false;
    var in_jobs = false;
    var lines = std.mem.splitScalar(u8, existing, '\n');
    while (lines.next()) |line| {
        if (line.len > 0 and line[0] != ' ' and line[0] != '#') {
            in_jobs = std.mem.eql(u8, std.mem.trimEnd(u8, line, " \r"), "jobs:");
            continue;
        }
        if (!in_jobs) continue;
        const name = jobKey(line) orelse continue;
        var known = false;
        for (generated_jobs) |job| known = known or std.mem.eql(u8, job, name);
        for (drops) |job| known = known or std.mem.eql(u8, job, name);
        if (known) continue;
        if (hasJob(generated, name)) continue;
        undeclared = name;
        missing = true;
    }
    if (missing) return error.UndeclaredCallerJob;
}

/// Whether `caller` opens a job named `name`.
fn hasJob(caller: []const u8, name: []const u8) bool {
    var lines = std.mem.splitScalar(u8, caller, '\n');
    while (lines.next()) |line| if (jobKey(line)) |key| if (std.mem.eql(u8, key, name)) return true;
    return false;
}

/// The job a line opens: `  name:` and nothing else but a comment.
fn jobKey(line: []const u8) ?[]const u8 {
    if (line.len < 4 or line[0] != ' ' or line[1] != ' ' or line[2] == ' ' or line[2] == '#') return null;
    const colon = std.mem.findScalar(u8, line, ':') orelse return null;
    const rest = std.mem.trim(u8, line[colon + 1 ..], " \r");
    if (rest.len != 0 and rest[0] != '#') return null;
    return line[2..colon];
}

const default_cron = "23 3 * * *";

/// The triggers `ci/workflow.json` asks for beyond the dispatch and the pull request.
const Triggers = struct { push: []const u8, schedule: []const u8, nightly_tier: []const u8 };

/// `attest` adds the push trigger on main that checks the commit's recorded merge or release run;
/// `nightly` is `false`, or `{ "cron": ..., "tier": ... }` (default: release at 03:23 UTC).
fn triggers(a: std.mem.Allocator, config: src.Value) !Triggers {
    const nightly = src.get(config, "nightly");
    if (nightly != .null and nightly != .bool and nightly != .object) return error.InvalidNightly;
    var cron: []const u8 = default_cron;
    var tier: []const u8 = "release";
    if (nightly == .object) {
        for (nightly.object.keys()) |key| if (!std.mem.eql(u8, key, "cron") and !std.mem.eql(u8, key, "tier")) return error.InvalidNightly;
        cron = try src.string(src.get(nightly, "cron"), default_cron);
        tier = try src.string(src.get(nightly, "tier"), "release");
        var fields: usize = 0;
        var parts = std.mem.tokenizeScalar(u8, cron, ' ');
        while (parts.next()) |part| : (fields += 1) {
            for (part) |byte| if (!std.ascii.isDigit(byte) and std.mem.findScalar(u8, "*/,-", byte) == null) return error.InvalidNightly;
        }
        if (fields != 5) return error.InvalidNightly;
        if (!std.mem.eql(u8, tier, "fast") and !std.mem.eql(u8, tier, "merge") and !std.mem.eql(u8, tier, "release")) return error.InvalidNightly;
    }
    const off = nightly == .bool and !nightly.bool;
    return .{
        .push = if (std.mem.eql(u8, try boolean(config, "attest"), "true")) "  push:\n    branches: [main]\n" else "",
        .schedule = if (off) "" else try a.print("  schedule:\n    - cron: '{s}'\n", .{cron}),
        .nightly_tier = tier,
    };
}

pub fn render(a: std.mem.Allocator, config: src.Value, pin: []const u8, directory: []const u8, own: bool, workflow: []const u8) ![]const u8 {
    // Every writer in renderAllocating is memory-backed. Its only write
    // failure is allocation exhaustion; preserve the allocator error contract.
    return renderAllocating(a, config, pin, directory, own, workflow) catch |err| switch (err) {
        error.WriteFailed => error.OutOfMemory,
        else => err,
    };
}

fn renderAllocating(a: std.mem.Allocator, config: src.Value, pin: []const u8, directory: []const u8, own: bool, workflow: []const u8) ![]const u8 {
    if (config != .object) return error.InvalidWorkflowConfig;
    if (!own) {
        if (pin.len != 40) return error.InvalidPreflightPin;
        for (pin) |byte| if (!std.ascii.isHex(byte) or std.ascii.isUpper(byte)) return error.InvalidPreflightPin;
    }
    try relative(directory, true);
    var matrices: std.Io.Writer.Allocating = .init(a);
    defer matrices.deinit();
    for ([_]matrix.Tier{ .fast, .merge, .release }) |tier| {
        const tiers = try matrix.split(a, config, try matrix.plan(a, config, tier), tier);
        for ([_][]const matrix.Job{ tiers.native, tiers.compile, tiers.run }, [_][]const u8{ "", "-compile", "-run" }) |group, suffix| {
            if (tier == .fast and suffix.len != 0) continue;
            try matrices.writer.print("      {t}{s}-matrix: >-\n        {s}\n", .{ tier, suffix, try std.json.Stringify.valueAlloc(a, .{ .include = group }, .{}) });
        }
    }
    const gate = if (own) "./.github/workflows/zig.yml" else try a.print("pedronaugusto/preflight/.github/workflows/zig.yml@{s}", .{pin});
    const when = try triggers(a, config);
    const tokens = [_][]const u8{ "@WORKFLOW@", "@GATE@", "@PIN@", "@DIRECTORY@", "@PUSH@", "@SCHEDULE@", "@NIGHTLY@", "@MATRICES@", "@WINDOWS_GIT@", "@COMPILE_ONCE@" };
    const values = [_][]const u8{ workflow, gate, if (own) "${{ github.sha }}" else pin, try std.json.Stringify.valueAlloc(a, directory, .{}), when.push, when.schedule, when.nightly_tier, matrices.written(), try boolean(config, "windows_git_latest"), try boolean(config, "compile_once") };
    var text: std.Io.Writer.Allocating = .init(a);
    defer text.deinit();
    var offset: usize = 0;
    while (offset < template.len) {
        var matched = false;
        for (tokens, values) |token, value| {
            if (std.mem.startsWith(u8, template[offset..], token)) {
                try text.writer.writeAll(value);
                offset += token.len;
                matched = true;
                break;
            }
        }
        if (!matched) {
            try text.writer.writeByte(template[offset]);
            offset += 1;
        }
    }
    return text.toOwnedSlice();
}

fn boolean(config: src.Value, name: []const u8) ![]const u8 {
    const value = src.get(config, name);
    return switch (value) {
        .null => "false",
        .bool => if (value.bool) "true" else "false",
        else => error.InvalidWorkflowBoolean,
    };
}

fn relative(path: []const u8, directory: bool) !void {
    if (directory and std.mem.eql(u8, path, ".")) return;
    if (path.len == 0 or std.Io.Dir.path.isAbsolute(path) or std.mem.findScalar(u8, path, '\\') != null) return error.InvalidWorkflowPath;
    var parts = std.mem.splitScalar(u8, path, '/');
    while (parts.next()) |part| {
        if (part.len == 0 or std.mem.eql(u8, part, ".") or std.mem.eql(u8, part, "..") or std.mem.eql(u8, part, ".git")) return error.InvalidWorkflowPath;
        for (part) |byte| if (byte < 32 or byte == 127) return error.InvalidWorkflowPath;
    }
}

/// Validates and renders everything before opening the sole output. Existing
/// directories and files are opened without following symlinks. This is a
/// regeneration write, not a durable/crash-atomic publication operation.
pub fn write(c: src.Context, path: []const u8, text: []const u8) !void {
    try relative(path, false);
    if (!std.mem.endsWith(u8, path, ".yml") and !std.mem.endsWith(u8, path, ".yaml")) return error.InvalidWorkflowPath;
    var dir = try c.directory().openDir(c.io, ".", .{ .follow_symlinks = false });
    defer dir.close(c.io);
    var parts = std.mem.splitScalar(u8, path, '/');
    var part = parts.next().?;
    while (parts.next()) |next| {
        const child = try dir.openDir(c.io, part, .{ .follow_symlinks = false });
        dir.close(c.io);
        dir = child;
        part = next;
    }
    const file = dir.openFile(c.io, part, .{ .mode = .read_write, .follow_symlinks = false }) catch |err| switch (err) {
        error.FileNotFound => try dir.createFile(c.io, part, .{ .exclusive = true }),
        else => return err,
    };
    defer file.close(c.io);
    if ((try file.stat(c.io)).kind != .file) return error.InvalidWorkflowOutput;
    try file.setLength(c.io, 0);
    var buffer: [4096]u8 = undefined;
    var writer = file.writer(c.io, &buffer);
    try writer.interface.writeAll(text);
    try writer.interface.flush();
}

